"""Look-ahead risk checklist for strategies that use a large language model (LLM).

An LLM trained on text up to date C "knows" what happened before C. If the backtest asks it about dates
before C, the model may be remembering the outcome instead of predicting it. This check is a RISK SCORE
computed from what the strategy owner declares (llm_checklist.json); it is not a memorisation test,
which needs model access. Because it rests on declarations that cannot be verified offline, it never
returns PASS: with an LLM it is always NEEDS_REVIEW, with the priority set by the score.

Checklist keys: uses_llm, model_name, model_training_cutoff, backtest_start, backtest_end,
uses_company_names, uses_tickers, uses_explicit_dates, uses_news_or_filings_text, anonymized_entities,
retrieval_pit_filtered, pit_model, post_cutoff_evaluation, memorization_probe_done.

Main reference: Glasserman, P. and Lin, C. (2023), "Assessing Look-Ahead Bias in Stock Return Predictions
Generated by GPT Sentiment Analysis", arXiv:2309.17322 (anonymising company names). Other items follow the
general principle of temporal sanitation (each decision may only use information available at its date);
docs/CHECKS.md lists further literature, flagged where the citation was not independently verified.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from datetime import date, timedelta
from typing import Any

import pandas as pd

from .. import stats
from ..findings import NEEDS_REVIEW, AuditResult
from ..inputs import Package
from . import missing_inputs, not_executable

BLOCK = "statistics"
CUTOFF_UNCERTAINTY_DAYS = 240  # ~8 months grey zone around the declared cutoff
POST_CUTOFF_MIN_OBS = 126
BANDS = [(60, "high"), (35, "medium"), (0, "low")]


@dataclass(frozen=True)
class Item:
    key: str
    question: str
    weight: float
    risky_if: bool | None  # value that implies risk (None = computed item)


ITEMS = [
    Item("temporal_exposure", "Share of the backtest window before the model's training cutoff", 35, None),
    Item("uses_company_names", "The prompt includes company names", 12, True),
    Item("uses_tickers", "The prompt includes tickers", 6, True),
    Item("uses_explicit_dates", "The prompt includes explicit event dates", 6, True),
    Item("uses_news_or_filings_text", "Texts the model may have seen in training (news, filings) are passed", 8, True),
    Item("anonymized_entities", "Companies, dates and identifying figures are anonymised", 6, False),
    Item("retrieval_pit_filtered", "Tools and retrieval are filtered as-of each decision date", 10, False),
    Item("pit_model", "A model with a cutoff before each decision date is used", 0, False),
    Item("post_cutoff_evaluation", "Results are reported for a period after the cutoff", 9, False),
    Item("memorization_probe_done", "It was tested whether the model remembers prices or outcomes of the period", 8,
         False),
]


def _d(x: Any) -> date | None:
    if x is None or x == "":
        return None
    if isinstance(x, date):
        return x
    s = str(x)
    if len(s) == 7:  # YYYY-MM
        s += "-01"
    try:
        return pd.Timestamp(s).date()
    except Exception:
        return None


def exposure(start: date, end: date, cutoff: date) -> tuple[float, float]:
    """(share of the window before the cutoff, share inside the +-8 month grey zone)."""
    total = max(1, (end - start).days)
    before = max(0, (min(end, cutoff) - start).days)
    lo, hi = cutoff - timedelta(days=CUTOFF_UNCERTAINTY_DAYS), cutoff + timedelta(days=CUTOFF_UNCERTAINTY_DAYS)
    grey = max(0, (min(end, hi) - max(start, lo)).days)
    return min(1.0, before / total), min(1.0, grey / total)


def score_checklist(cfg: dict, start: date | None = None, end: date | None = None) -> dict[str, Any]:
    if not cfg.get("uses_llm", True):
        return {"applies": False, "score": 0.0, "items": []}
    start = _d(cfg.get("backtest_start")) or start
    end = _d(cfg.get("backtest_end")) or end
    cutoff = _d(cfg.get("model_training_cutoff"))
    pit_model = cfg.get("pit_model") is True
    anonym = cfg.get("anonymized_entities") is True
    items, total = [], 0.0
    for it in ITEMS:
        if it.key == "temporal_exposure":
            if pit_model:
                val, state = 0.0, "point-in-time model: no exposure"
            elif cutoff is None or start is None or end is None:
                val, state = 1.0, "not declared (cutoff or window): worst case assumed"
            else:
                before, grey = exposure(start, end, cutoff)
                val = min(1.0, before + 0.25 * grey)
                state = (f"{before:.0%} of the window ({start} to {end}) is before the cutoff {cutoff}; {grey:.0%} falls "
                         "in the +-8 month grey zone")
            pts = it.weight * val
        else:
            v = cfg.get(it.key)
            weight = it.weight
            if it.key in ("uses_company_names", "uses_tickers", "uses_explicit_dates") and anonym:
                weight *= 0.25
            if v is None:
                pts, state = weight * 0.5, "not declared (half the weight counted)"
            elif v == it.risky_if:
                pts, state = weight, "risk"
            else:
                pts, state = 0.0, "ok"
        total += pts
        items.append({"item": it.key, "question": it.question, "state": state, "points": round(pts, 1),
                      "weight": it.weight})
    max_pts = sum(i.weight for i in ITEMS)
    return {"applies": True, "score": round(100 * total / max_pts, 1), "items": items,
            "model": cfg.get("model_name", "-"), "cutoff": str(cutoff) if cutoff else None,
            "window": [str(start) if start else None, str(end) if end else None]}


def check_llm_lookahead(pkg: Package, res: AuditResult, returns=None, dates=None) -> None:
    title = "LLM look-ahead risk"
    if pkg.llm_checklist is None:
        missing_inputs(res, "llm_lookahead_risk", BLOCK, title, ["llm_checklist"])
        return
    start, end = (dates[0], dates[-1]) if dates else (None, None)
    sc = score_checklist(pkg.llm_checklist, start, end)
    res.metrics["llm_checklist"] = sc
    if not sc["applies"]:
        not_executable(res, "llm_lookahead_risk", BLOCK, title,
                       "not applicable: the checklist declares that no LLM is used (declaration not verifiable)")
        return
    priority = next(p for thr, p in BANDS if sc["score"] >= thr)
    risky = [i["item"] for i in sc["items"] if i["points"] > 0]
    ev: list[dict] = list(sc["items"])
    extra = ""
    cutoff = _d(pkg.llm_checklist.get("model_training_cutoff"))
    if cutoff and returns is not None and dates:
        s_pre, s_post, n_pre, n_post = stats.subperiod_sharpes(returns, dates, cutoff)
        ppy = int(pkg.conv("periods_per_year"))
        k = math.sqrt(ppy)
        decay = {"item": "post_cutoff_decay", "sharpe_before_annualised": s_pre * k if s_pre is not None else None,
                 "sharpe_after_annualised": s_post * k if s_post is not None else None, "n_before": n_pre,
                 "n_after": n_post}
        ev.append(decay)
        if s_pre is not None and s_post is not None and n_post >= POST_CUTOFF_MIN_OBS:
            if s_pre * k > 0.5 and s_post < 0.5 * s_pre:
                extra = (f" The annualised Sharpe falls from {s_pre * k:.2f} before the cutoff to {s_post * k:.2f} after "
                         "it: the typical pattern of a model remembering the past.")
                priority = "high"
        else:
            extra = (f" Not enough observations after the cutoff to measure the decay ({n_post}, "
                     f"{POST_CUTOFF_MIN_OBS} needed).")
    res.add("llm_lookahead_risk", BLOCK, NEEDS_REVIEW, f"LLM look-ahead risk score: {sc['score']:.0f}/100",
            f"Model {sc.get('model')} with declared cutoff {sc.get('cutoff')}; window {sc['window'][0]} to "
            f"{sc['window'][1]}. Items with risk: {', '.join(risky) or 'none'}. The score rests on declarations; "
            "memorisation is not tested offline." + extra, ev,
            "Weighted checklist (temporal exposure to the training cutoff with a +-8 month grey zone, identifying "
            "information in prompts, as-of filtering of retrieval, post-cutoff evaluation, memorisation probe); "
            "undeclared items count half; Sharpe before vs after the cutoff when returns are available.",
            action="Evaluate on a period after the model cutoff, anonymise entities and dates, and probe the model for "
                   "memorised outcomes.", priority=priority, inputs=["llm_checklist"])
