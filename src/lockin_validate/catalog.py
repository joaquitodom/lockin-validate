def explain(check_id: str) -> dict[str, Any]:
    c = CHECKS.get(check_id)
    if c is None:
        return {"error": f"unknown check {check_id!r}", "available": sorted(CHECKS)}
    out = {"id": check_id, **{k: v for k, v in c.items() if k != "refs"},
           "references": [REF[r] for r in c["refs"]], "inputs": REQUIREMENTS.get(check_id, {})}
    return out


def render_explain(check_id: str) -> str:
    e = explain(check_id)
    if "error" in e:
        return e["error"] + "\nAvailable checks: " + ", ".join(e["available"])
    req = e["inputs"]
    lines = [f"{e['id']} ({e['block']}): {e['title']}", "",
             f"What it checks: {e['what']}", f"Why it matters: {e['why']}", f"How to fix: {e['fix']}",
             f"Allows concluding: {e['allows']}", f"Does not allow: {e['does_not_allow']}"]
    if e.get("motivation"):
        lines.append(f"Motivation (LockIn case study): {e['motivation']}")
    lines += [
             "Required inputs: " + (", ".join(req.get("required", [])) or "none"),
             "Optional inputs: " + (", ".join(req.get("optional", [])) or "none")]
    if e["references"]:
        lines += ["References:"] + [f"  - {r}" for r in e["references"]]
    lines += ["Statuses: CONFIRMED_ERROR, NEEDS_REVIEW, NOT_EXECUTABLE (with reason), INFO (note, not an alert), "
              "PASS (within scope)."]
    return "\n".join(lines)
